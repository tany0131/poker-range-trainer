const searchFaq = (query) => {
  const needle = query.trim().toLowerCase()
  if (!needle) return FAQ
  return FAQ.filter(
    (entry) => entry.q.toLowerCase().includes(needle) || entry.a.toLowerCase().includes(needle),
  )
}
